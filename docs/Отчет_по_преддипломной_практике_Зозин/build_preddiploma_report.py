def set_run_font(run, size=14, bold=False):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def set_paragraph_format(paragraph, first_indent=True, align=None, before=0, after=0, line=1.5):
    paragraph.paragraph_format.first_line_indent = Cm(1.25) if first_indent else Cm(0)
    paragraph.paragraph_format.space_before = Pt(before)
    paragraph.paragraph_format.space_after = Pt(after)
    paragraph.paragraph_format.line_spacing = line
    paragraph.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY


def p(doc, text="", *, align=None, first_indent=True, bold=False, size=14, before=0, after=0, line=1.5):
    paragraph = doc.add_paragraph()
    set_paragraph_format(paragraph, first_indent=first_indent, align=align, before=before, after=after, line=line)
    if text:
        run = paragraph.add_run(text)
        set_run_font(run, size=size, bold=bold)
    return paragraph


def h(doc, text, level=1):
    paragraph = doc.add_heading(level=level)
    paragraph.clear()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER if level == 1 else WD_ALIGN_PARAGRAPH.LEFT
    paragraph.paragraph_format.first_line_indent = Cm(0 if level == 1 else 1.25)
    paragraph.paragraph_format.space_before = Pt(8 if level == 1 else 6)
    paragraph.paragraph_format.space_after = Pt(6)
    paragraph.paragraph_format.line_spacing = 1.5
    run = paragraph.add_run(text.upper() if level == 1 else text)
    set_run_font(run, size=14, bold=True)
    return paragraph


def set_cell_text(cell, text, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, size=12):
    cell.text = ""
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    paragraph = cell.paragraphs[0]
    set_paragraph_format(paragraph, first_indent=False, align=align, line=1.15, after=0)
    for idx, part in enumerate(str(text).split("\n")):
        if idx:
            paragraph.add_run().add_break()
        run = paragraph.add_run(part)
        set_run_font(run, size=size, bold=bold)


def table(doc, caption, headers, rows, widths_cm=None):
    p(doc, caption, first_indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, bold=False, before=6, after=3)
    tbl = doc.add_table(rows=1, cols=len(headers))
    tbl.style = "Table Grid"
    tbl.autofit = False
    for i, header in enumerate(headers):
        set_cell_text(tbl.rows[0].cells[i], header, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    for row in rows:
        cells = tbl.add_row().cells
        for i, value in enumerate(row):
            set_cell_text(cells[i], value, align=WD_ALIGN_PARAGRAPH.LEFT if i else WD_ALIGN_PARAGRAPH.CENTER)
    if widths_cm:
        for row in tbl.rows:
            for i, width in enumerate(widths_cm):
                row.cells[i].width = Cm(width)
    p(doc, "", first_indent=False, line=1.0, after=2)
    return tbl


def bullet_list(doc, items):
    for item in items:
        paragraph = doc.add_paragraph(style="List Bullet")
        set_paragraph_format(paragraph, first_indent=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, line=1.5)
        run = paragraph.add_run(item)
        set_run_font(run)


def number_list(doc, items):
    for item in items:
        paragraph = doc.add_paragraph(style="List Number")
        set_paragraph_format(paragraph, first_indent=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, line=1.5)
        run = paragraph.add_run(item)
        set_run_font(run)


def add_picture(doc, image_name, caption, width_cm=14.5):
    image_path = IMG_DIR / image_name
    if not image_path.exists():
        return
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run()
    run.add_picture(str(image_path), width=Cm(width_cm))
    p(doc, caption, align=WD_ALIGN_PARAGRAPH.CENTER, first_indent=False, size=12, after=6, line=1.0)


