IMPROVED_BOX_DIAGRAM = r'''def draw_box_diagram(path: Path, title: str, boxes: list[tuple[int, int, int, int, str]], arrows: list[tuple[int, int, int, int]]):
    img = Image.new("RGB", (1400, 850), "white")
    draw = ImageDraw.Draw(img)
    try:
        font_title = ImageFont.truetype("arial.ttf", 34)
        font = ImageFont.truetype("arial.ttf", 24)
        font_small = ImageFont.truetype("arial.ttf", 20)
    except Exception:
        font_title = font = font_small = ImageFont.load_default()
    draw.text((40, 30), title, fill=(0, 0, 0), font=font_title)
    for x1, y1, x2, y2, label in boxes:
        draw.rounded_rectangle((x1, y1, x2, y2), radius=18, outline=(0, 0, 0), width=3, fill=(245, 247, 250))
        lines = label.split("\n")
        total_h = len(lines) * 30
        start_y = y1 + ((y2 - y1) - total_h) / 2
        for line in lines:
            active_font = font_small if len(line) > 32 else font
            bbox = draw.textbbox((0, 0), line, font=active_font)
            draw.text((x1 + ((x2 - x1) - (bbox[2] - bbox[0])) / 2, start_y), line, fill=(0, 0, 0), font=active_font)
            start_y += 30

    def arrow_head(x1: int, y1: int, x2: int, y2: int):
        if abs(x2 - x1) >= abs(y2 - y1):
            if x2 >= x1:
                pts = [(x2, y2), (x2 - 18, y2 - 10), (x2 - 18, y2 + 10)]
            else:
                pts = [(x2, y2), (x2 + 18, y2 - 10), (x2 + 18, y2 + 10)]
        else:
            if y2 >= y1:
                pts = [(x2, y2), (x2 - 10, y2 - 18), (x2 + 10, y2 - 18)]
            else:
                pts = [(x2, y2), (x2 - 10, y2 + 18), (x2 + 10, y2 + 18)]
        draw.polygon(pts, fill=(0, 0, 0))

    for x1, y1, x2, y2 in arrows:
        if x1 == x2 or y1 == y2:
            points = [(x1, y1), (x2, y2)]
        else:
            if abs(x2 - x1) >= abs(y2 - y1):
                mid = x1 + (x2 - x1) // 2
                points = [(x1, y1), (mid, y1), (mid, y2), (x2, y2)]
            else:
                mid = y1 + (y2 - y1) // 2
                points = [(x1, y1), (x1, mid), (x2, mid), (x2, y2)]
        for start, end in zip(points, points[1:]):
            draw.line((*start, *end), fill=(0, 0, 0), width=3)
        arrow_head(*points[-2], *points[-1])
    img.save(path)


'''

