def replace_function(source: str, function_name: str, replacement: str) -> str:
    start = source.index(f"def {function_name}(")
    next_def = source.index("\ndef ", start + 1)
    return source[:start] + replacement + source[next_def + 1:]


def crop_er_images() -> None:
    out_dir = GENERATED_DIR / "V5_generated" / "images"
    out_dir.mkdir(parents=True, exist_ok=True)
    for src_name, dst_name in [
        ("er-core.png", "er_core_cropped.png"),
        ("er-gamification.png", "er_gamification_cropped.png"),
        ("er-content.png", "er_content_cropped.png"),
        ("er-roles.png", "er_roles_cropped.png"),
    ]:
        src = ER_DIR / src_name
        dst = out_dir / dst_name
        img = Image.open(src).convert("RGB")
        bg = Image.new("RGB", img.size, "white")
        bbox = ImageChops.difference(img, bg).getbbox()
        if bbox:
            pad = 20
            left = max(bbox[0] - pad, 0)
            top = max(bbox[1] - pad, 0)
            right = min(bbox[2] + pad, img.width)
            bottom = min(bbox[3] + pad, img.height)
            img = img.crop((left, top, right, bottom))
        img.save(dst)


